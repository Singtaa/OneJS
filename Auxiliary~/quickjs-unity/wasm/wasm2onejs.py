#!/usr/bin/env python3
"""
Turns a .wasm into C that a OneJS native module library is built from.

    python3 wasm2onejs.py <module.wasm> <name> <out dir> [--wasm2c <path>]

Writes <name>.c and <name>.h (wasm2c's translation of the module) and
<name>_onejs.c, which describes it to OneJS through onejs_wasm.h: every
function export as a thunk taking its arguments as uint64_t slots, every
import calling back into the host the same way, and the module's sha256, so
the glue that loads it can refuse a module it was not generated against.
Compile the three with wasm-rt-impl.c and wasm-rt-mem-impl.c from the same
WABT release (build-module.sh does).

The thunks are read from wasm2c's header rather than from the binary: each
import and export there is a comment naming it, then its C prototype, and the
prototype is what the thunk has to call. A header shape this does not
recognise stops the run with the line it could not read, rather than leaving
a function out.
"""

import argparse
import hashlib
import os
import re
import subprocess
import sys

WASM2C_VERSION = "1.0.42"

TYPES = {"u32": "i", "u64": "l", "f32": "f", "f64": "d"}

# How a slot becomes a parameter, and a result becomes a slot.
FROM_SLOT = {
    "u32": "(u32)a[{i}]",
    "u64": "(u64)a[{i}]",
    "f32": "onejs_f32(a[{i}])",
    "f64": "onejs_f64(a[{i}])",
}
TO_SLOT = {
    "u32": "(uint64_t){v}",
    "u64": "(uint64_t){v}",
    "f32": "onejs_f32_bits({v})",
    "f64": "onejs_f64_bits({v})",
}

COMMENT = re.compile(r"^/\* (import|export): '((?:[^'\\]|\\.)*)'(?: '((?:[^'\\]|\\.)*)')? \*/$")
PROTO = re.compile(r"^(\w+\*?) (\w+)\(([^)]*)\);$")


def unescape(text):
    """wasm2c writes a name's awkward bytes as \\XX in its comments."""
    return re.sub(r"\\([0-9A-Fa-f]{2})", lambda m: chr(int(m.group(1), 16)), text)


def c_string(text):
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def signature(params, result):
    return "".join(TYPES[p] for p in params) + ">" + ("" if result == "void" else TYPES[result])


def check_type(t, line):
    if t != "void" and t not in TYPES:
        sys.exit(f"wasm2onejs: a type this does not handle ({t}) in: {line}")


def read_header(path, name):
    """The imports and function exports wasm2c declared, in its order."""
    lines = open(path, encoding="utf-8").read().split("\n")
    imports, exports = [], []
    instance_type = f"w2c_{name}*"
    instantiate = None
    for n, line in enumerate(lines):
        if line.startswith(f"void wasm2c_{name}_instantiate("):
            instantiate = line
        match = COMMENT.match(line)
        if not match:
            continue
        kind, first, second = match.group(1), match.group(2), match.group(3)
        proto = PROTO.match(lines[n + 1])
        if not proto:
            sys.exit(f"wasm2onejs: no prototype after: {line}")
        result, symbol, params = proto.group(1), proto.group(2), [p.strip() for p in proto.group(3).split(",")]
        if kind == "import":
            # struct w2c_<module>*, then the parameters.
            host = params[0]
            if not (host.startswith("struct w2c_") and host.endswith("*")):
                sys.exit(f"wasm2onejs: an import without its module first: {lines[n + 1]}")
            rest = params[1:]
            for t in [result, *rest]:
                check_type(t, lines[n + 1])
            imports.append({"module": unescape(first), "name": unescape(second), "symbol": symbol,
                            "struct": host[len("struct "):-1], "params": rest, "result": result})
        else:
            # Memory, tables and globals answer a pointer and take only the
            # instance; they are reached through the instance, not as calls.
            if result.endswith("*"):
                continue
            if params[0] != instance_type:
                sys.exit(f"wasm2onejs: an export without its instance first: {lines[n + 1]}")
            rest = params[1:]
            for t in [result, *rest]:
                check_type(t, lines[n + 1])
            exports.append({"name": unescape(first), "symbol": symbol, "params": rest, "result": result})
    if instantiate is None:
        sys.exit(f"wasm2onejs: no wasm2c_{name}_instantiate in {path}")
    # The import modules in the order instantiate takes them.
    structs = re.findall(r"struct (w2c_\w+)\*", instantiate)
    return imports, exports, structs


def generate(name, sha256, imports, exports, structs, memory_symbol):
    out = []
    w = out.append
    w(f"/* Generated by wasm2onejs.py from {name}.wasm (sha256 {sha256}). Do not edit. */")
    w("#include <stdio.h>")
    w("#include <stdlib.h>")
    w("#include <string.h>")
    w(f'#include "{name}.h"')
    w('#include "wasm-rt-impl.h"')
    w('#include "wasm-rt-exceptions.h"')
    w('#include "onejs_wasm.h"')
    w("")
    w("#ifdef _WIN32")
    w("#define ONEJS_WASM_EXPORT __declspec(dllexport)")
    w("#else")
    w('#define ONEJS_WASM_EXPORT __attribute__((visibility("default")))')
    w("#endif")
    w("")
    w("static inline f32 onejs_f32(uint64_t v) { uint32_t b = (uint32_t)v; f32 f; memcpy(&f, &b, 4); return f; }")
    w("static inline f64 onejs_f64(uint64_t v) { f64 d; memcpy(&d, &v, 8); return d; }")
    w("static inline uint64_t onejs_f32_bits(f32 f) { uint32_t b; memcpy(&b, &f, 4); return b; }")
    w("static inline uint64_t onejs_f64_bits(f64 d) { uint64_t b; memcpy(&b, &d, 8); return b; }")
    w("")
    w("/* Every import module the instance needs, all with the same shape: the host, and whether it threw. */")
    for s in structs:
        w(f"struct {s} {{ void* host; onejs_wasm_import_call call; int* threw; }};")
    w("")
    w("typedef struct {")
    w(f"    w2c_{name} module;")
    for i, s in enumerate(structs):
        w(f"    struct {s} imports{i};")
    w("    int threw;")
    w(f"}} onejs_{name}_instance;")
    w("")
    for index, imp in enumerate(imports):
        params = ", ".join([f"struct {imp['struct']}* host"] + [f"{t} p{i}" for i, t in enumerate(imp["params"])])
        w(f"/* import: {imp['module']} {imp['name']} */")
        w(f"{imp['result']} {imp['symbol']}({params}) {{")
        w(f"    uint64_t a[{max(1, len(imp['params']))}] = {{0}};")
        w("    uint64_t r[1] = {0};")
        for i, t in enumerate(imp["params"]):
            w(f"    a[{i}] = {TO_SLOT[t].format(v=f'p{i}')};")
        w(f"    if (host->call(host->host, {index}, a, r) != 0) {{")
        w("        *host->threw = 1;")
        w("        wasm_rt_trap(WASM_RT_TRAP_UNREACHABLE);")
        w("    }")
        if imp["result"] != "void":
            w(f"    return {FROM_SLOT[imp['result']].format(i=0).replace('a[', 'r[')};")
        else:
            w("    (void)r;")
        w("}")
    w("")
    for n, exp in enumerate(exports):
        args = ", ".join(["&i->module"] + [FROM_SLOT[t].format(i=k) for k, t in enumerate(exp["params"])])
        w(f"static void onejs_x{n}(void* instance, const uint64_t* a, uint64_t* r) {{")
        w(f"    onejs_{name}_instance* i = (onejs_{name}_instance*)instance;")
        if not exp["params"]:
            w("    (void)a;")
        call = f"{exp['symbol']}({args})"
        if exp["result"] == "void":
            w(f"    {call};")
            w("    (void)r;")
        else:
            w(f"    r[0] = {TO_SLOT[exp['result']].format(v=call)};")
        w("}")
    w("")
    w(f"static const onejs_wasm_import onejs_{name}_imports[] = {{")
    for imp in imports:
        w(f"    {{ {c_string(imp['module'])}, {c_string(imp['name'])}, {c_string(signature(imp['params'], imp['result']))} }},")
    if not imports:
        w("    { 0, 0, 0 },")
    w("};")
    w("")
    w(f"static const onejs_wasm_export onejs_{name}_exports[] = {{")
    for n, exp in enumerate(exports):
        w(f"    {{ {c_string(exp['name'])}, {c_string(signature(exp['params'], exp['result']))}, onejs_x{n} }},")
    w("};")
    w("")
    w(f"""/*
 * Runs fn(instance, args, results) with the module's traps caught. Saves and
 * restores the trap target around it, because a call can arrive while another
 * is running (the module calls an import, the import calls back in), and the
 * inner one must not leave the outer one's target pointing at a frame that
 * has returned.
 */
static int onejs_{name}_call(void* instance, onejs_wasm_thunk thunk, const uint64_t* args, uint64_t* results,
                             char* error, size_t error_size) {{
    onejs_{name}_instance* i = (onejs_{name}_instance*)instance;
    wasm_rt_jmp_buf outer = g_wasm_rt_jmp_buf;
#if WASM_RT_STACK_DEPTH_COUNT
    uint32_t outer_depth = wasm_rt_saved_call_stack_depth;
#endif
    WASM_RT_UNWIND_TARGET* outer_target = wasm_rt_get_unwind_target();
    int outer_threw = i->threw;
    i->threw = 0;
    int code = ONEJS_WASM_OK;
    /*
     * wasm_rt_impl_try, but without saving the signal mask: sigsetjmp(buf, 1)
     * is a system call (two on macOS, with sigaltstack) on every call into the
     * module, and measured as most of a raycast's cost under QuickJS. Only a
     * trap raised from a signal handler needs the mask back, and these
     * libraries are built without one (no guard pages).
     */
    WASM_RT_SAVE_STACK_DEPTH();
    wasm_rt_set_unwind_target(&g_wasm_rt_jmp_buf);
    wasm_rt_trap_t trap = (wasm_rt_trap_t)WASM_RT_SETJMP_EXN(g_wasm_rt_jmp_buf);
    if (trap == WASM_RT_TRAP_NONE) {{
        thunk(instance, args, results);
    }} else if (i->threw) {{
        code = ONEJS_WASM_HOST_THREW;
    }} else {{
        code = ONEJS_WASM_TRAPPED;
        if (error && error_size) snprintf(error, error_size, "%s", wasm_rt_strerror(trap));
    }}
    g_wasm_rt_jmp_buf = outer;
#if WASM_RT_STACK_DEPTH_COUNT
    wasm_rt_saved_call_stack_depth = outer_depth;
#endif
    wasm_rt_set_unwind_target(outer_target);
    i->threw = outer_threw;
    return code;
}}

static void onejs_{name}_start(void* instance, const uint64_t* a, uint64_t* r) {{
    onejs_{name}_instance* i = (onejs_{name}_instance*)instance;
    (void)a; (void)r;
    wasm2c_{name}_instantiate(&i->module{"".join(f", &i->imports{k}" for k in range(len(structs)))});
}}

static void* onejs_{name}_instantiate(void* host, onejs_wasm_import_call call, char* error, size_t error_size) {{
    if (!wasm_rt_is_initialized()) wasm_rt_init();
    onejs_{name}_instance* i = (onejs_{name}_instance*)calloc(1, sizeof(onejs_{name}_instance));
    if (!i) {{
        if (error && error_size) snprintf(error, error_size, "out of memory");
        return NULL;
    }}
{"".join(f'''    i->imports{k}.host = host;
    i->imports{k}.call = call;
    i->imports{k}.threw = &i->threw;
''' for k in range(len(structs)))}    /* Instantiating runs the module's start function and data segments, which can trap. */
    if (onejs_{name}_call(i, onejs_{name}_start, NULL, NULL, error, error_size) != ONEJS_WASM_OK) {{
        free(i);
        return NULL;
    }}
    return i;
}}

static void onejs_{name}_free(void* instance) {{
    onejs_{name}_instance* i = (onejs_{name}_instance*)instance;
    wasm2c_{name}_free(&i->module);
    free(i);
}}

static uint8_t* onejs_{name}_memory(void* instance, uint64_t* size) {{
    wasm_rt_memory_t* m = {memory_symbol}(&((onejs_{name}_instance*)instance)->module);
    *size = m->size;
    return m->data;
}}

static uint64_t onejs_{name}_grow(void* instance, uint64_t pages) {{
    return wasm_rt_grow_memory({memory_symbol}(&((onejs_{name}_instance*)instance)->module), pages);
}}

static const onejs_wasm_module onejs_{name}_module = {{
    ONEJS_WASM_ABI,
    {c_string(name)},
    {c_string(sha256)},
    {len(imports)},
    onejs_{name}_imports,
    {len(exports)},
    onejs_{name}_exports,
    onejs_{name}_instantiate,
    onejs_{name}_free,
    onejs_{name}_memory,
    onejs_{name}_grow,
    onejs_{name}_call,
}};

ONEJS_WASM_EXPORT const onejs_wasm_module* onejs_wasm_{name}(void) {{
    return &onejs_{name}_module;
}}
""")
    return "\n".join(out)


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("wasm")
    parser.add_argument("name")
    parser.add_argument("out")
    parser.add_argument("--wasm2c", default="wasm2c")
    args = parser.parse_args()

    if not re.fullmatch(r"[a-z][a-z0-9]*", args.name):
        sys.exit("wasm2onejs: a module name is lower case letters and digits, starting with a letter (wasm2c rewrites _ in names)")
    version = subprocess.run([args.wasm2c, "--version"], capture_output=True, text=True).stdout.strip()
    if version != WASM2C_VERSION:
        # The thunks are only as right as the header they were read from, and
        # the runtime files compiled beside them must be the same release's.
        sys.exit(f"wasm2onejs: needs wasm2c {WASM2C_VERSION}, found {version or 'none'} at {args.wasm2c}")

    data = open(args.wasm, "rb").read()
    sha256 = hashlib.sha256(data).hexdigest()
    os.makedirs(args.out, exist_ok=True)
    c_path = os.path.join(args.out, f"{args.name}.c")
    subprocess.run([args.wasm2c, args.wasm, "-n", args.name, "-o", c_path], check=True)

    header = os.path.join(args.out, f"{args.name}.h")
    imports, exports, structs = read_header(header, args.name)
    memory = re.search(rf"wasm_rt_memory_t\* (w2c_{args.name}_memory)\(", open(header, encoding="utf-8").read())
    if not memory:
        sys.exit(f"wasm2onejs: {args.name} exports no memory named 'memory'")
    with open(os.path.join(args.out, f"{args.name}_onejs.c"), "w", encoding="utf-8") as f:
        f.write(generate(args.name, sha256, imports, exports, structs, memory.group(1)))
    print(f"{args.name}: {len(imports)} imports, {len(exports)} function exports, sha256 {sha256}")


if __name__ == "__main__":
    main()
